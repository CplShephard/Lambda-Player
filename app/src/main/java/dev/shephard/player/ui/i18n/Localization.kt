// Keep each language's map construction outside <clinit> and pass only one map per call.
private val EN = createEN()
private val TR = createTR(EN)
private val ZH = createZH(EN)
private val ES = createES(EN)
private val RU = createRU(EN)
private val KA = createKA(EN)
private val AR = createAR(EN)

val AllLanguages: List<Strings> = listOf(EN, TR, ZH, ES, RU, KA, AR)

fun stringsFor(code: String): Strings =
    AllLanguages.firstOrNull { it.code == code } ?: EN

val LocalStrings = compositionLocalOf { EN }

object LocalizedText {
    val current: Strings
        @Composable
        @ReadOnlyComposable
        get() = LocalStrings.current
}
